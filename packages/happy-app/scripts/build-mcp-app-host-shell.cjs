const fs = require('node:fs');
const path = require('node:path');
const esbuild = require('esbuild');

const packageRoot = path.resolve(__dirname, '..');
const entry = path.join(packageRoot, 'mcp-app-sandbox', 'hostShell.ts');
const output = path.join(packageRoot, 'sources', 'components', 'tools', 'mcpApps', 'generated', 'hostShellBundle.ts');

const built = esbuild.buildSync({
    entryPoints: [entry],
    bundle: true,
    minify: true,
    platform: 'browser',
    format: 'iife',
    target: ['ios15', 'chrome100'],
    write: false,
    legalComments: 'none',
    sourcemap: false,
    charset: 'utf8',
});

const javascript = built.outputFiles[0].text.replaceAll('</script', '<\\/script');
const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; frame-src data: blob: 'self'; img-src data: blob:; font-src data:; media-src 'none'; connect-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'"><meta http-equiv="Permissions-Policy" content="camera=(), microphone=(), geolocation=(), clipboard-read=(), clipboard-write=()"><style>html,body{margin:0;width:100%;height:100%;overflow:hidden;background:transparent}</style></head><body><script>${javascript}</script></body></html>`;
const source = `// Generated by scripts/build-mcp-app-host-shell.cjs. Do not edit.\nexport const MCP_APP_HOST_SHELL_HTML = ${JSON.stringify(html)};\n`;

if (process.argv.includes('--check')) {
    const current = fs.existsSync(output) ? fs.readFileSync(output, 'utf8') : '';
    if (current !== source) {
        process.stderr.write('MCP App Host Shell bundle is out of date. Run build:mcp-app-host-shell.\n');
        process.exitCode = 1;
    }
} else {
    fs.mkdirSync(path.dirname(output), { recursive: true });
    fs.writeFileSync(output, source);
}
